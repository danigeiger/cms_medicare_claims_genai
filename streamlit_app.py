"""Streamlit UI for the existing CMS Medicare Claims GenAI FastAPI backend."""
import os
import requests
import streamlit as st

st.set_page_config(page_title="Medicare Codebook AI", page_icon="🏥", layout="wide")
st.markdown("""<style>.block-container{max-width:1100px;padding-top:2rem}div[data-testid="stMetric"]{background:#1c293b;border:1px solid #34465c;border-radius:12px;padding:20px}div[data-testid="stMetric"] label{color:#d2e1f0!important}div[data-testid="stMetricValue"]{color:#ffffff!important}div[data-testid="stMetricDelta"]{color:#80dfb0!important}</style>""", unsafe_allow_html=True)

API_URL = os.getenv("RAG_API_URL", "http://127.0.0.1:8000").rstrip("/")
try:
    API_URL = st.secrets.get("RAG_API_URL", API_URL).rstrip("/")
except (FileNotFoundError, KeyError):
    pass

st.title("Medicare Codebook AI")
st.caption("A retrieval-augmented assistant for exploring CMS Medicare Fee-for-Service claims variables")
st.info("Research demonstration: answers describe CMS codebook variables, not individual patient claims or clinical recommendations.")

with st.sidebar:
    st.header("Project")
    st.markdown("**Jessica D. Geiger**  \nM.S. Data Science")
    st.link_button("View source on GitHub", "https://github.com/danigeiger/cms_medicare_claims_genai")
    st.divider()
    st.caption("The live assistant uses the existing FastAPI backend. API credentials remain on the server, not in this interface.")

ask, eval_tab, architecture = st.tabs(["Ask Medicare AI", "Model Evaluation", "Architecture"])

with ask:
    st.subheader("Find a CMS claims variable")
    st.write("Ask about a field in the Medicare Fee-for-Service claims codebook.")
    examples = ["What variable identifies the beneficiary's race?", "Which variable identifies the Medicare carrier?", "What field represents the claim-level Part B deductible?"]
    question = st.selectbox("Try an example, or enter your own question below", ["Write my own question"] + examples)
    typed = st.text_input("Your question", value="" if question == "Write my own question" else question, placeholder="e.g. Which field identifies the beneficiary's race?")
    if st.button("Find variable", type="primary", disabled=not typed.strip()):
        with st.spinner("Searching the CMS codebook and generating an answer..."):
            try:
                response = requests.post(f"{API_URL}/ask", json={"query": typed.strip()}, timeout=90)
                response.raise_for_status()
                data = response.json()
                if not isinstance(data, dict):
                    raise ValueError("Unexpected response format")
                st.success("Answer received")
                st.metric("CMS variable", data.get("variable") or "No confirmed match")
                st.markdown(f"**Label:** {data.get('label') or 'Not available'}")
                st.markdown("**Explanation**")
                st.write(data.get("explanation") or "No explanation returned.")
                with st.expander("Raw structured response"):
                    st.json(data)
            except requests.exceptions.ConnectionError:
                st.error("Cannot reach the RAG API. Start FastAPI locally, or configure RAG_API_URL for your deployed backend.")
            except requests.exceptions.Timeout:
                st.error("The request timed out. The embedding and reranking models may still be loading.")
            except (requests.exceptions.RequestException, ValueError) as exc:
                st.error(f"The request could not be completed: {exc}")
    st.caption("Answers are generated by the existing RAG pipeline and should be checked against official CMS documentation.")

with eval_tab:
    st.subheader("50-question held-out evaluation")
    a, b, c = st.columns(3)
    a.metric("Retrieval Recall@5", "96%", "48 / 50", delta_arrow="off", delta_color="off")
    b.metric("Exact-match accuracy", "92%", "46 / 50", delta_arrow="off", delta_color="off")
    c.metric("API errors", "0", "50 evaluated", delta_arrow="off", delta_color="off")
    st.write("The held-out questions were derived from the same CMS codebook, with no overlapping expected variable identifiers from the 20-question development benchmark. These are recorded benchmark results, not live production metrics.")
    st.markdown("**Known errors in the recorded evaluation**")
    st.dataframe([
        {"Question": "Accepted assignment", "Issue": "Expected variable not in top five"},
        {"Question": "Medicare carrier identifier", "Issue": "Expected variable not in top five"},
        {"Question": "Care-plan oversight organization", "Issue": "Incorrect final variable selection"},
        {"Question": "Claim-level Part B deductible liability", "Issue": "Incorrect final variable selection"},
    ], hide_index=True, use_container_width=True)
    st.caption("Source: project README and evaluation_results/ in the GitHub repository. This benchmark does not establish accuracy on independently collected real-user questions.")

with architecture:
    st.subheader("How the RAG pipeline works")
    st.code("CMS codebook PDF → structured variable records → MiniLM embeddings → persistent ChromaDB\nUser question → query embedding → exact NumPy retrieval (top 20) → CrossEncoder reranking\n→ Reciprocal Rank Fusion → top 5 variable definitions → GPT-4.1-mini → structured answer", language="text")
    st.markdown("**Technology:** Python, SentenceTransformers, ChromaDB, NumPy, CrossEncoder, RRF, OpenAI, Pydantic, FastAPI, Streamlit.")
    st.markdown("**Scope:** This project retrieves CMS codebook definitions. It does not perform fraud detection, analyze real patient claims, or provide clinical advice.")
    st.link_button("Read technical documentation", "https://github.com/danigeiger/cms_medicare_claims_genai")
